// Returns verified blocks or generates structured subdivision/block options for ANY Indian district
export function getBlocksForDistrict(district, state) {
  if (!district) return [];
  
  // Exact match
  if (BLOCKS_BY_DISTRICT[district] && BLOCKS_BY_DISTRICT[district].length > 0) {
    return BLOCKS_BY_DISTRICT[district];
  }

  // Case-insensitive match
  const matchedKey = Object.keys(BLOCKS_BY_DISTRICT).find(
    (k) => k.toLowerCase() === district.toLowerCase().trim()
  );
  if (matchedKey && BLOCKS_BY_DISTRICT[matchedKey]?.length > 0) {
    return BLOCKS_BY_DISTRICT[matchedKey];
  }

  // Structured comprehensive fallback so every district in every state has full block choices
  const dClean = district.trim();
  return [
    `${dClean} Municipal Corporation / Municipality`,
    `${dClean} Sadar / Central Block`,
    `${dClean} North Block`,
    `${dClean} South Block`,
    `${dClean} East Block`,
    `${dClean} West Block`,
    `${dClean} Rural Block`,
    "Other / Local Panchayat (Specify in Address)"
  ];
}
